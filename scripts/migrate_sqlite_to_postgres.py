"""One-off, guarded SQLite -> PostgreSQL migration for TRIADA-INV.

Dry-run by default. Pass --apply to write. The target must be empty (or have
only empty TRIADA tables); existing rows are never overwritten.
"""
from __future__ import annotations

import argparse
import asyncio
import os
import shutil
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg import sql

TABLES = (
    "published_news",
    "bot_stats",
    "recommendations",
    "bot_meta",
    "user_portfolios",
    "user_alerts",
    "user_watchlists",
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS published_news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id TEXT UNIQUE, title TEXT, source TEXT, url TEXT,
    published_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, post_type TEXT
);
CREATE TABLE IF NOT EXISTS bot_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT UNIQUE, posts_count INTEGER DEFAULT 0, errors_count INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT, subject TEXT, recommendation TEXT, price_at_post DOUBLE PRECISION,
    posted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, checked INTEGER DEFAULT 0,
    correct INTEGER, price_after DOUBLE PRECISION, signal_id TEXT, entry_time TIMESTAMP,
    category TEXT DEFAULT 'market_move', confidence DOUBLE PRECISION, source TEXT,
    horizon_hours INTEGER DEFAULT 24, pnl_percent DOUBLE PRECISION,
    max_drawdown_percent DOUBLE PRECISION, direction_correct INTEGER
);
CREATE TABLE IF NOT EXISTS bot_meta (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS user_portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT, ticker TEXT, quantity DOUBLE PRECISION, avg_price DOUBLE PRECISION,
    added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id, ticker)
);
CREATE TABLE IF NOT EXISTS user_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT, ticker TEXT, alert_type TEXT DEFAULT 'price',
    target_price DOUBLE PRECISION, direction TEXT, params TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, triggered INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS user_watchlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT, ticker TEXT, added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, ticker)
);
"""

def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sqlite", default=os.getenv("SQLITE_PATH", "data/bot.db"))
    parser.add_argument("--apply", action="store_true", help="Perform migration; without this flag only inspect.")
    return parser.parse_args()

def main():
    args = parse_args()
    source = Path(args.sqlite)
    target = os.getenv("DATABASE_URL", "").strip()
    if not source.is_file():
        sys.exit(f"SQLite source does not exist: {source}")
    if not target:
        sys.exit("DATABASE_URL is required; no data was changed.")
    if args.apply:
        backup = source.with_name(
            f"{source.name}.pre-postgres-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}.bak"
        )
        shutil.copy2(source, backup)
        print(f"SQLite safety copy: {backup}")

    with sqlite3.connect(f"file:{source.resolve()}?mode=ro", uri=True) as local:
        local.row_factory = sqlite3.Row
        counts = {}
        for table in TABLES:
            exists = local.execute(
                "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()
            counts[table] = local.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0] if exists else 0

        print("Source row counts:")
        for table, count in counts.items():
            print(f"  {table}: {count}")

        with psycopg.connect(target, autocommit=False) as remote:
            with remote.cursor() as cur:
                cur.execute(SCHEMA)
                remote.commit()
                target_counts = {}
                for table in TABLES:
                    cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table)))
                    target_counts[table] = cur.fetchone()[0]
                if any(target_counts.values()):
                    sys.exit(
                        "Target is not empty; refusing to merge/overwrite data. "
                        f"Target counts: {target_counts}"
                    )
                if not args.apply:
                    remote.rollback()
                    print("DRY RUN only: target schema was inspected/created then rolled back; no rows copied.")
                    print("Review counts, then rerun with --apply to migrate.")
                    return

                try:
                    for table in TABLES:
                        rows = local.execute(f'SELECT * FROM "{table}"').fetchall() if counts[table] else []
                        if not rows:
                            continue
                        columns = rows[0].keys()
                        statement = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                            sql.Identifier(table),
                            sql.SQL(", ").join(map(sql.Identifier, columns)),
                            sql.SQL(", ").join(sql.Placeholder() for _ in columns),
                        )
                        cur.executemany(statement, [tuple(row) for row in rows])
                    # Preserve generated IDs after importing explicit IDs.
                    for table in ("published_news", "bot_stats", "recommendations",
                                  "user_portfolios", "user_alerts", "user_watchlists"):
                        cur.execute(
                            "SELECT setval(pg_get_serial_sequence(%s, 'id'), "
                            "GREATEST(COALESCE((SELECT MAX(id) FROM " + table + "), 1), 1), "
                            "EXISTS(SELECT 1 FROM " + table + "))",
                            (table,),
                        )
                    remote.commit()
                except Exception:
                    remote.rollback()
                    raise

                for table, expected in counts.items():
                    cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table)))
                    actual = cur.fetchone()[0]
                    if actual != expected:
                        raise RuntimeError(f"Validation failed for {table}: expected {expected}, got {actual}")
                print("Migration committed and row counts verified:")
                for table, count in counts.items():
                    print(f"  {table}: {count}")

if __name__ == "__main__":
    main()
