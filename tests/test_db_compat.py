import unittest

from modules.db_compat import _translate


class PostgreSQLTranslationTests(unittest.TestCase):
    def test_pragma_table_info_becomes_information_schema_query(self):
        query, special = _translate("PRAGMA table_info(recommendations)")
        self.assertIn("information_schema.columns", query)
        self.assertEqual(special, "recommendations")

    def test_autoincrement_is_translated(self):
        query, special = _translate(
            "CREATE TABLE IF NOT EXISTS sample (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT)"
        )
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", query)
        self.assertIsNone(special)

    def test_insert_or_ignore_uses_conflict_clause(self):
        query, _ = _translate(
            "INSERT OR IGNORE INTO user_watchlists (user_id, ticker) VALUES (?, ?)"
        )
        self.assertIn("ON CONFLICT DO NOTHING", query)
        self.assertIn("VALUES (%s, %s)", query)

    def test_relative_hours_and_days_are_translated(self):
        hours, _ = _translate(
            "SELECT title FROM published_news WHERE published_at > datetime('now', ? || ' hours')"
        )
        days, _ = _translate(
            "SELECT COUNT(*) FROM recommendations WHERE posted_at >= datetime('now', ? || ' days')"
        )
        self.assertIn("(%s || ' hours')::interval", hours)
        self.assertIn("(%s || ' days')::interval", days)

    def test_recommendation_horizon_is_translated(self):
        query, _ = _translate(
            "SELECT id FROM recommendations WHERE checked = 0 AND datetime('now') >= "
            "datetime(posted_at, '+' || COALESCE(horizon_hours, 24) || ' hours')"
        )
        self.assertIn("CURRENT_TIMESTAMP >= posted_at", query)
        self.assertIn("INTERVAL '1 hour'", query)


if __name__ == "__main__":
    unittest.main()
