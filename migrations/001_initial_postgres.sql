-- PostgreSQL schema corresponding to modules/storage.py.
-- Apply only when intentionally migrating storage from SQLite to PostgreSQL.
-- This file does not switch the running bot to PostgreSQL by itself.

CREATE TABLE IF NOT EXISTS published_news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id TEXT UNIQUE,
    title TEXT,
    source TEXT,
    url TEXT,
    published_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    post_type TEXT
);

CREATE TABLE IF NOT EXISTS bot_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT UNIQUE,
    posts_count INTEGER DEFAULT 0,
    errors_count INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT,
    subject TEXT,
    recommendation TEXT,
    price_at_post DOUBLE PRECISION,
    posted_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    checked INTEGER DEFAULT 0,
    correct INTEGER,
    price_after DOUBLE PRECISION,
    signal_id TEXT,
    entry_time TIMESTAMPTZ,
    category TEXT DEFAULT 'market_move',
    confidence DOUBLE PRECISION,
    source TEXT,
    horizon_hours INTEGER DEFAULT 24,
    pnl_percent DOUBLE PRECISION,
    max_drawdown_percent DOUBLE PRECISION,
    direction_correct INTEGER
);

CREATE TABLE IF NOT EXISTS bot_meta (
    key TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS user_portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    ticker TEXT,
    quantity DOUBLE PRECISION,
    avg_price DOUBLE PRECISION,
    added_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, ticker)
);

CREATE TABLE IF NOT EXISTS user_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    ticker TEXT,
    alert_type TEXT DEFAULT 'price',
    target_price DOUBLE PRECISION,
    direction TEXT,
    params TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    triggered INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS user_watchlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    ticker TEXT,
    added_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, ticker)
);


-- Durable raw-news archive and processing state.
CREATE TABLE IF NOT EXISTS news_items (
    news_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    source TEXT,
    source_domain TEXT,
    url TEXT,
    summary TEXT,
    published_at TEXT,
    first_seen_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    processing_status TEXT DEFAULT 'collected',
    analysis_json TEXT,
    post_type TEXT
);
CREATE INDEX IF NOT EXISTS idx_news_items_published_at ON news_items(published_at);
CREATE INDEX IF NOT EXISTS idx_news_items_status ON news_items(processing_status, last_seen_at);

ALTER TABLE news_items ADD COLUMN IF NOT EXISTS source_count INTEGER DEFAULT 1;
ALTER TABLE news_items ADD COLUMN IF NOT EXISTS corroborating_sources_json TEXT;
ALTER TABLE news_items ADD COLUMN IF NOT EXISTS retry_count INTEGER DEFAULT 0;
