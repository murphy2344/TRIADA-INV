"""Small async database compatibility layer for SQLite and PostgreSQL.

SQLite remains the default. Setting DATABASE_URL enables PostgreSQL.
The public surface intentionally mirrors the subset of aiosqlite used by
modules.storage so callers keep their existing API.
"""
from __future__ import annotations

import os
import re
from typing import Any

import aiosqlite as _sqlite

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
POSTGRES_ENABLED = DATABASE_URL.startswith(("postgres://", "postgresql://"))


def _translate(query: str) -> tuple[str, Any]:
    """Translate the SQLite SQL subset used by storage.py to PostgreSQL."""
    q = query.strip()
    pragma = bool(re.match(r"(?is)^PRAGMA\s+table_info\s*\(", q))
    if pragma:
        match = re.search(r"(?is)^PRAGMA\s+table_info\s*\(\s*([\w]+)\s*\)", q)
        table = match.group(1)
        return (
            "SELECT ordinal_position - 1 AS cid, column_name AS name "
            "FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = %s "
            "ORDER BY ordinal_position",
            table,
        )
    q = re.sub(r"(?i)INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", q)
    q = re.sub(r"(?i)INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", q)
    ignore_insert = query.lstrip().upper().startswith("INSERT OR IGNORE")
    q = re.sub(
        r"datetime\('now',\s*\?\s*\|\|\s*'\s*hours'\s*\)",
        "(CURRENT_TIMESTAMP + (%s || ' hours')::interval)", q, flags=re.I,
    )
    q = re.sub(
        r"datetime\('now',\s*\?\s*\|\|\s*'\s*days'\s*\)",
        "(CURRENT_TIMESTAMP + (%s || ' days')::interval)", q, flags=re.I,
    )
    q = re.sub(
        r"datetime\('now'\)\s*>=\s*datetime\(posted_at,\s*'\+'\s*\|\|\s*COALESCE\(horizon_hours,\s*24\)\s*\|\|\s*'\s*hours'\s*\)",
        "CURRENT_TIMESTAMP >= posted_at + (COALESCE(horizon_hours, 24) * INTERVAL '1 hour')",
        q, flags=re.I,
    )
    q = q.replace("?", "%s")
    if ignore_insert:
        q = q.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return q, None


class _BufferedCursor:
    def __init__(self, rows, description, rowcount):
        self.rows = list(rows)
        self.description = description
        self.rowcount = rowcount
        self._index = 0

    async def fetchone(self):
        if self._index >= len(self.rows):
            return None
        row = self.rows[self._index]
        self._index += 1
        return row

    async def fetchall(self):
        rows = self.rows[self._index:]
        self._index = len(self.rows)
        return rows

    async def close(self):
        return None

    async def __aenter__(self):
        return self

    async def __aexit__(self, exc_type, exc, tb):
        await self.close()


class _Execute:
    """An execute result supporting await and async-with usage."""
    def __init__(self, connection, query, params):
        self.connection = connection
        self.query = query
        self.params = params
        self._cursor = None

    async def _run(self):
        if self._cursor is None:
            self._cursor = await self.connection._execute(self.query, self.params)
        return self._cursor

    def __await__(self):
        return self._run().__await__()

    async def __aenter__(self):
        return await self._run()

    async def __aexit__(self, exc_type, exc, tb):
        cursor = await self._run()
        await cursor.__aexit__(exc_type, exc, tb)


class Connection:
    def __init__(self, target, **kwargs):
        self.target = target
        self.kwargs = kwargs
        self._db = None
        self._pg = POSTGRES_ENABLED and target == DATABASE_URL

    async def __aenter__(self):
        if self._pg:
            import psycopg
            self._db = await psycopg.AsyncConnection.connect(
                self.target, connect_timeout=10
            )
        else:
            self._db = await _sqlite.connect(self.target, **self.kwargs)
        return self

    async def __aexit__(self, exc_type, exc, tb):
        if self._db is not None:
            if self._pg:
                if exc_type:
                    await self._db.rollback()
                else:
                    await self._db.commit()
                await self._db.close()
            else:
                await self._db.__aexit__(exc_type, exc, tb)

    def execute(self, query, parameters=()):
        return _Execute(self, query, parameters)

    async def _execute(self, query, parameters=()):
        if not self._pg:
            return await self._db.execute(query, parameters)
        translated, special = _translate(query)
        async with self._db.cursor() as cursor:
            if isinstance(special, str):
                await cursor.execute(translated, (special,))
            else:
                await cursor.execute(translated, parameters or ())
            rows = await cursor.fetchall() if cursor.description else []
            description = cursor.description
            rowcount = cursor.rowcount
        return _BufferedCursor(rows, description, rowcount)

    async def commit(self):
        await self._db.commit()

    async def rollback(self):
        await self._db.rollback()


def connect(database, **kwargs):
    """Return a SQLite or PostgreSQL connection wrapper."""
    target = DATABASE_URL if POSTGRES_ENABLED else database
    return Connection(target, **kwargs)
